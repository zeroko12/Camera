        static ContrastBrightnessEffect()
        {
            _pixelShader = new PixelShader();
            using (var ms = new MemoryStream(_byteCode))
            {
                _pixelShader.SetStreamSource(ms);
            }
        }

        public ContrastBrightnessEffect()
        {
            PixelShader = _pixelShader;
            UpdateShaderValue(InputProperty);
            UpdateShaderValue(ContrastProperty);
            UpdateShaderValue(BrightnessProperty);
        }

        public static readonly DependencyProperty InputProperty =
            RegisterPixelShaderSamplerProperty("Input", typeof(ContrastBrightnessEffect), 0);

        public Brush Input
        {
            get => (Brush)GetValue(InputProperty);
            set => SetValue(InputProperty, value);
        }

        public static readonly DependencyProperty ContrastProperty =
            DependencyProperty.Register(
                nameof(Contrast),
                typeof(double),
                typeof(ContrastBrightnessEffect),
                new UIPropertyMetadata(1.0, PixelShaderConstantCallback(0)));

        public double Contrast
        {
            get => (double)GetValue(ContrastProperty);
            set => SetValue(ContrastProperty, value);
        }

        public static readonly DependencyProperty BrightnessProperty =
            DependencyProperty.Register(
                nameof(Brightness),
                typeof(double),
                typeof(ContrastBrightnessEffect),
                new UIPropertyMetadata(0.0, PixelShaderConstantCallback(1)));

        public double Brightness
        {
